/// Pixels of `text` as (x, y) offsets for a scale of 1; each glyph is 6 wide with spacing.
pub fn pixels(text: &str) -> Vec<(u32, u32)> {
    let mut out = Vec::new();
    for (i, ch) in text.to_uppercase().chars().enumerate() {
        let Some((_, rows)) = GLYPHS.iter().find(|(c, _)| *c == ch) else {
            continue;
        };
        for (y, row) in rows.iter().enumerate() {
            for x in 0..5 {
                if row & (1 << (4 - x)) != 0 {
                    out.push((i as u32 * 6 + x as u32, y as u32));
                }
            }
        }
    }
    out
}

pub fn width(text: &str) -> u32 {
    text.chars().count() as u32 * 6
}
